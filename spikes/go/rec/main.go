// Command rec runs a TUI inside a PTY (xpty) mirrored by a headless VT
// emulator (charmbracelet/x/vt), drives it with a small script, and records
// the raw output bytes plus emulator screen snapshots taken mid-session.
//
// Usage:
//
//	rec -cols 120 -rows 36 -dir /path/cwd -out prefix -steps "wait:6|paste:hi|enter|wait:15|snap:a" -- cmd args...
//
// Steps: wait:<sec> | paste:<text> | text:<text> | enter | ctrlc | key:<raw> | snap:<label>
// Each snap writes <out>.<label>.vt.txt and appends "<label>\t<byte offset>" to <out>.snaps.
package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"runtime"
	"strconv"
	"strings"
	"sync"
	"time"

	"github.com/charmbracelet/x/ansi"
	"github.com/charmbracelet/x/vt"
	"github.com/charmbracelet/x/xpty"
)

func main() {
	cols := flag.Int("cols", 120, "columns")
	rows := flag.Int("rows", 36, "rows")
	dir := flag.String("dir", "", "working directory")
	out := flag.String("out", "rec", "output prefix")
	steps := flag.String("steps", "wait:3", "pipe-separated steps")
	maxSecs := flag.Float64("max", 90, "hard deadline in seconds")
	flag.Parse()
	time.AfterFunc(time.Duration(*maxSecs*float64(time.Second)), func() {
		fmt.Fprintln(os.Stderr, "deadline reached; exiting")
		os.Exit(3)
	})
	args := flag.Args()
	if len(args) == 0 {
		fmt.Fprintln(os.Stderr, "missing command")
		os.Exit(2)
	}

	pty, err := xpty.NewPty(*cols, *rows)
	must(err)
	defer pty.Close()

	emu := vt.NewSafeEmulator(*cols, *rows)

	// Mode state is updated from emulator callbacks, which run inside emu.Write,
	// so it gets its own lock (streamMu is held around emu.Write).
	var (
		modeMu     sync.Mutex
		paste2004  bool
		modeEvents []string
		altEvents  int
	)
	emu.SetCallbacks(vt.Callbacks{
		EnableMode: func(m ansi.Mode) {
			modeMu.Lock()
			defer modeMu.Unlock()
			modeEvents = append(modeEvents, fmt.Sprintf("+%v", m))
			if m == ansi.ModeBracketedPaste {
				paste2004 = true
			}
		},
		DisableMode: func(m ansi.Mode) {
			modeMu.Lock()
			defer modeMu.Unlock()
			modeEvents = append(modeEvents, fmt.Sprintf("-%v", m))
			if m == ansi.ModeBracketedPaste {
				paste2004 = false
			}
		},
		AltScreen: func(bool) {
			modeMu.Lock()
			altEvents++
			modeMu.Unlock()
		},
	})

	cmd := exec.Command(args[0], args[1:]...)
	cmd.Dir = *dir
	cmd.Env = append(os.Environ(), "TERM=xterm-256color", "COLORTERM=truecolor")
	must(pty.Start(cmd))

	raw, err := os.Create(*out + ".raw")
	must(err)
	defer raw.Close()

	// Terminal replies (DA, CPR, ...) generated by the emulator go back to the program.
	go func() { _, _ = io.Copy(pty, emu) }()

	// streamMu keeps the raw file, the emulator state and the byte counter in
	// sync so a snapshot matches an exact prefix of the raw stream.
	var (
		streamMu sync.Mutex
		total    int64
	)
	readDone := make(chan struct{})
	go func() {
		defer close(readDone)
		buf := make([]byte, 64*1024)
		for {
			n, err := pty.Read(buf)
			if n > 0 {
				streamMu.Lock()
				_, _ = raw.Write(buf[:n])
				_, _ = emu.Write(buf[:n])
				total += int64(n)
				streamMu.Unlock()
			}
			if err != nil {
				return
			}
		}
	}()

	for _, st := range strings.Split(*steps, "|") {
		kind, arg, _ := strings.Cut(st, ":")
		switch kind {
		case "wait":
			secs, _ := strconv.ParseFloat(arg, 64)
			time.Sleep(time.Duration(secs * float64(time.Second)))
		case "paste":
			modeMu.Lock()
			bp := paste2004
			modeMu.Unlock()
			if bp {
				_, _ = pty.Write([]byte("\x1b[200~" + arg + "\x1b[201~"))
			} else {
				_, _ = pty.Write([]byte(arg))
			}
			fmt.Printf("paste (bracketed=%v)\n", bp)
		case "text":
			_, _ = pty.Write([]byte(arg))
		case "enter":
			_, _ = pty.Write([]byte("\r"))
		case "ctrlc":
			_, _ = pty.Write([]byte{0x03})
		case "key":
			_, _ = pty.Write([]byte(arg))
		case "snap":
			streamMu.Lock()
			off, screen := total, emu.String()
			streamMu.Unlock()
			must(os.WriteFile(fmt.Sprintf("%s.%s.vt.txt", *out, arg), []byte(screen), 0o644))
			f, err := os.OpenFile(*out+".snaps", os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
			must(err)
			fmt.Fprintf(f, "%s\t%d\n", arg, off)
			f.Close()
		}
	}

	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()
	_ = xpty.WaitProcess(ctx, cmd)
	select {
	case <-readDone:
	case <-time.After(500 * time.Millisecond):
	}

	var ms runtime.MemStats
	runtime.ReadMemStats(&ms)
	modeMu.Lock()
	fmt.Printf("bytes=%d alt_events=%d alt_now=%v paste2004_now=%v modes=%v\n",
		total, altEvents, emu.IsAltScreen(), paste2004, modeEvents)
	modeMu.Unlock()
	fmt.Printf("heap_alloc=%.1fMB sys=%.1fMB scrollback_lines=%d\n",
		float64(ms.HeapAlloc)/1e6, float64(ms.Sys)/1e6, emu.ScrollbackLen())
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
